#!/usr/bin/env python
"""Regenerate the vendored architecture file under ``standalone/``.

    python scripts/export_standalone.py

``standalone/host_prior`` is a copy of just enough of this package to *load* a
trained prior, for dropping into a separate inference package that should not
depend on the training stack.  Everything in it is small and stable except the
architecture, which is the one file where a silent difference would be
catastrophic: a vendored ``NCSNpp`` whose module fields have drifted from the
trainer's produces a pytree that no longer matches the checkpoint, and the
failure is a shape error at best and a wrong model at worst.

So the architecture is not transcribed, it is **generated**: this copies
``nn/ncsnpp.py`` byte for byte and rewrites its three internal imports to point
at ``_support``.  ``tests/test_standalone.py`` runs this and fails if the
checked-in copy differs, so a change to the architecture that is not exported
is caught here rather than in somebody's forward model.
"""

from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src" / "rubin_host_prior" / "nn" / "ncsnpp.py"
TARGET = ROOT / "standalone" / "host_prior" / "_net.py"

#: The only edit. Everything else must come across unchanged -- in particular
#: the module field declarations, whose order and static-ness *are* the
#: checkpoint format.
REWRITE = (
    "from ..config import NCSNppConfig\n"
    "from .energy import EnergyModel\n"
    "from .layers import FourierFeatures, get_activation\n",
    "from ._support import EnergyModel, FourierFeatures, NCSNppConfig, get_activation\n",
)

HEADER = '''# Generated by scripts/export_standalone.py -- do not edit.
#
# A byte-for-byte copy of rubin_host_prior/nn/ncsnpp.py with its three internal
# imports repointed at ._support. The module field declarations below are the
# checkpoint format: their order and their static-ness decide how equinox lays
# out the pytree, so an edit here silently stops trained weights loading.
# Change the trainer's copy and re-run the exporter instead.
'''


def render() -> str:
    text = SOURCE.read_text()
    old, new = REWRITE
    if text.count(old) != 1:
        raise SystemExit(
            f"{SOURCE} no longer has the expected import block:\n\n{old}\n"
            f"The exporter rewrites exactly that and nothing else. Update "
            f"REWRITE here to match, and check that no *new* internal import "
            f"was added -- the standalone copy has no package to resolve one."
        )
    return HEADER + text.replace(old, new, 1)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true",
                   help="exit non-zero if the checked-in copy is stale, and "
                        "write nothing. What CI runs")
    args = p.parse_args()

    want = render()
    if args.check:
        have = TARGET.read_text() if TARGET.exists() else ""
        if have != want:
            raise SystemExit(
                f"{TARGET.relative_to(ROOT)} is stale. Run "
                f"`python scripts/export_standalone.py` and commit the result."
            )
        print(f"{TARGET.relative_to(ROOT)} is up to date")
        return
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(want)
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(want.splitlines()):,} lines)")


if __name__ == "__main__":
    main()
